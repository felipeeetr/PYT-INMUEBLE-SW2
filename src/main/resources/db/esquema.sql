CREATE TABLE IF NOT EXISTS PROPIETARIO (
    identificacion VARCHAR PRIMARY KEY,
    nombre VARCHAR NOT NULL,
    correo VARCHAR NOT NULL
);

CREATE TABLE IF NOT EXISTS INMUEBLE (
    chip VARCHAR PRIMARY KEY,
    fecha_compra DATE NOT NULL,
    direccion VARCHAR NOT NULL,
    estado VARCHAR NOT NULL CHECK (estado IN ('DISPONIBLE', 'ARRENDADO', 'VENDIDO')),
    tipo VARCHAR NOT NULL CHECK (tipo IN ('APARTAMENTO', 'CASA')),
    propietario_id VARCHAR NOT NULL REFERENCES PROPIETARIO(identificacion) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS APARTAMENTO (
    chip VARCHAR PRIMARY KEY REFERENCES INMUEBLE(chip) ON DELETE CASCADE,
    numero_piso INT NOT NULL CHECK (numero_piso > 0)
);

CREATE TABLE IF NOT EXISTS CASA (
    chip VARCHAR PRIMARY KEY REFERENCES INMUEBLE(chip) ON DELETE CASCADE,
    cantidad_pisos INT NOT NULL CHECK (cantidad_pisos > 0)
);

CREATE TABLE IF NOT EXISTS SOTANO (
    chip_casa VARCHAR PRIMARY KEY REFERENCES CASA(chip) ON DELETE CASCADE,
    area_m2 DECIMAL(12, 2) NOT NULL CHECK (area_m2 > 0),
    tipo_uso VARCHAR NOT NULL CHECK (tipo_uso IN ('BODEGA', 'PARQUEADERO', 'VIVIENDA'))
);

